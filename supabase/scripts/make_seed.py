"""Generate supabase/migrations/002_catalog_seed.sql from frontend/src/lib/catalog.ts.

The seed copies the website's built-in catalog (prices, opening prices, Shopee ids, stock and
colour-name overrides) plus the opening-promo end date, so the database starts identical to the
live site. Re-running the SQL resets those rows to the built-in values (upsert).

usage (from repo root): python supabase/scripts/make_seed.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
src = (ROOT / "frontend/src/lib/catalog.ts").read_text(encoding="utf-8")

def q(value):
    return "null" if value is None else "'" + str(value).replace("'", "''") + "'"

body = src[src.index("export const products"):src.index("export const campaignImages")]
blocks = re.split(r"\n  \{\n", body)[1:]
products, variants = [], []
for order, block in enumerate(blocks):
    head = re.search(r'id: "([^"]+)", name: "([^"]+)", price: (\d+)(?:, openingPrice: (\d+))?', block)
    pid, name, price, opening = head.group(1), head.group(2), int(head.group(3)), head.group(4)
    shopee = re.search(r'shopeeItemId: "(\d+)"', block)
    products.append((pid, name, price, int(opening) if opening else None, shopee.group(1) if shopee else None, order))
    for vorder, v in enumerate(re.finditer(r'variant\("([^"]+)", (\d+), "[^"]*", "[^"]*"(?:, "([^"]+)")?\)', block)):
        variants.append((pid, v.group(1), v.group(3), int(v.group(2)), vorder))

end = re.search(r'OPENING_PROMO_END = new Date\("([^"]+)"\)', src).group(1)
label = re.search(r'OPENING_PROMO_LABEL = "([^"]+)"', src).group(1)

lines = ["-- Generated by supabase/scripts/make_seed.py from frontend/src/lib/catalog.ts. Run after 001_catalog.sql.",
         "insert into public.products (id, name, price, opening_price, shopee_item_id, sort_index) values"]
lines.append(",\n".join(f"  ({q(p)}, {q(n)}, {pr}, {op if op is not None else 'null'}, {q(sh)}, {o})" for p, n, pr, op, sh, o in products))
lines.append("on conflict (id) do update set name = excluded.name, price = excluded.price, opening_price = excluded.opening_price,\n"
             "  shopee_item_id = excluded.shopee_item_id, sort_index = excluded.sort_index;\n")
lines.append("insert into public.product_variants (product_id, code, color_name, stock, sort_index) values")
lines.append(",\n".join(f"  ({q(p)}, {q(c)}, {q(cn)}, {s}, {o})" for p, c, cn, s, o in variants))
lines.append("on conflict (product_id, code) do update set color_name = excluded.color_name, stock = excluded.stock,\n"
             "  sort_index = excluded.sort_index;\n")
promo = json.dumps({"end": end, "label": label})
lines.append(f"insert into public.settings (key, value) values ('opening_promo', '{promo}'::jsonb)\n"
             "on conflict (key) do update set value = excluded.value;")
out = ROOT / "supabase/migrations/002_catalog_seed.sql"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out.relative_to(ROOT)}: {len(products)} products, {len(variants)} variants")
